// через пробел после области аргументов указывается тип возвращаемого функцией значения
func calculateIMT(userWeight, userHeight float64) (float64, error) {  // ключевое слово error обозначает возврат функцией ошибки в качестве одного из значений вывода
	if userHeight <= 0 || userWeight <= 0 {
		return 0, errors.New("NO_PARAMS_ERROR")  // метод библиотеки errors для создания простой ошибки с выводом текста ошибки 
	}
	IMT := userWeight / math.Pow(userHeight/100, IMTPower)
	return IMT, nil  // nil - отсутствие значения. Используется для вывода, если ошибок в работе функции не возникло
}

