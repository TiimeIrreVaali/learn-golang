func outputResult(imt float64) {
	result := fmt.Sprintf("Ваш индекс массы тела: %.2f", imt)
	fmt.Print(result)
	switch {  // если после switch указать переменную, то в case будут перечисляться её возможные значения. Если не указывать переменную в switch, её надо указать в case.
	case imt < 16: fmt.Println("\nУ Вас сильный дефицит массы тела")
	case imt < 18.5: fmt.Println("\nУ Вас недостаточная масса тела")
	case imt < 25: fmt.Println("\nУ Вас нормальная масса тела")
	case imt < 30: fmt.Println("\nУ Вас избыточная масса тела")
	case imt >= 30: fmt.Println("\nУ Вас ожирение")
	}

	/*
	Комментарий:
	Следует упомянуть ключевое слово fallthrough т.к. в отличие, например, от JS, в Go неявно присутствует break внутри каждого case, поэтому такой код работает корректно, 
	хотя пример IMT = 10 подходит под все условия. А если же нужно получить поведение "как в JS", то стоит использовать fallthrough, 
	тогда вычисление будет проваливаться в следующий case.
	*/
}

func getUserInput() (float64, float64) { // синтаксис функции с выводом нескольких значений: первые скобки - для аргументов, вторые - для выводимых значений
	var userWeight float64
	var userHeight float64
	fmt.Print("\nВведите свой рост (в сантиметрах): ")
	fmt.Scan(&userHeight) // метод для ввода и сохранения в переменную. Принимает указатель на переменную, а не саму переменную.
	fmt.Print("Введите свой вес (в килограммах): ")
	fmt.Scan(&userWeight)
	return userWeight, userHeight // вывод нескольких значений - через запятую
}

